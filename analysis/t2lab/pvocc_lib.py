# ------------------------------------------------------------------ arms, decisions, scoring
def colsets_o(cols):
    """{(arm, member): columns}: base / ogf = pvogf column sets (G.colsets); baseO / ogfO = the same + OCC_COLS appended."""
    cs = G.colsets(cols)
    for arm in ('base', 'ogf'):
        for m in ('np', 'id', 'full'):
            cs[(arm + 'O', m)] = list(cs[(arm, m)]) + OCC_COLS
    return cs


def mix(P, s, p, arm, seeds=None):
    """0.25 np + 0.25 id + 0.5 full of one arm; P = {seed: {(set, panel, member): P6}} or one dict; seed-averaged probabilities."""
    if seeds is None:
        return 0.25 * P[(s, p, f'{arm}_np')] + 0.25 * P[(s, p, f'{arm}_id')] + 0.5 * P[(s, p, f'{arm}_full')]
    return sum(mix(P[x], s, p, arm) for x in seeds) / len(seeds)


def lgb_fit_locked(get_X, y, w, cols, seed, n_trees=500, leaves=255):
    """G.lgb_fit (Dataset with params, constructed, float matrix freed, then boosting) with the matrix built under a file lock so that
    only one 185-column matrix exists at a time across the pvocc jobs (shared 24 GB machine)."""
    import lightgbm as lgb
    params = lab.lgb_params(num_leaves=leaves, learning_rate=0.05, min_data_in_leaf=40, seed=seed)
    with open(LOCK, 'w') as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        t1 = time.time()
        X = get_X(); assert X.shape == (len(y), len(cols)), (X.shape, len(y), len(cols))
        ds = lgb.Dataset(X, y, weight=w, feature_name=list(cols), params=params, free_raw_data=True)
        ds.construct(); del X; gc.collect()
        lab.log(f'  matrix + Dataset {len(y)} x {len(cols)} in {time.time() - t1:.0f}s (lock released)')
    return lgb.train(params, ds, n_trees)
