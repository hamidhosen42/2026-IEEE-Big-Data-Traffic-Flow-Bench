"""Generate the CatBoost T1 member kernels kaggle_jobs/t1_catb_member_{a,b,c,d}.py from the FD member t1_pipeline_v13a.py.

Changes vs the source (everything else identical: data loading, features (94 production FD columns), darkened train view,
row rng 9 / transductive rounds rng 10000 (= v13 rows), 15 % validation holdout, template prediction, outputs):
  (1) PANELS = the part's panels (4 parts, balanced by station count; ~2 large-panel equivalents each);
  (2) model = CatBoost RMSE residual regressors, depth 8 (CB_IT8 iterations) + depth 10 (CB_IT10) averaged 50/50, lr 0.12,
      l2 10, Bernoulli subsample 0.85, border_count 64 (anubisyy train_state.py family, iterations as in the lab
      analysis/t1lab/t1div_exp.py), fitted on at most CB_ROWS of the train + transductive rows (random subsample, rng 21);
  (3) SMOKE: tiny CatBoost (60 / 30 iterations).
Usage: t1catb_make_kernel.py [W_CATB=0.25]   (writes the 4 member kernels + t1_catb_swap.py + swap_fdrecon_k1.py; ast.parse)
"""
import ast, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(ROOT, 'kaggle_jobs', 't1_pipeline_v13a.py')
PARTS = {'a': ['D7_I405_N', 'D7_I10_W'], 'b': ['D7_I210_E', 'D7_I210_W', 'D12_I405_S'],
         'c': ['D12_I5_N', 'D12_I5_S'], 'd': ['D7_I10_E', 'D7_I405_S', 'D12_I405_N']}

DOC = '''"""Task 1 t1catb member (EXP_T1_CATB): CatBoost residual member on the v13 FD feature set, part {part} = {panels}.
Identical to kaggle_jobs/t1_pipeline_v13a.py (data loading, darkened train view, 94 production FD columns, row rng 9 and
transductive rounds rng 10000 = the v13 rows, 15 % validation holdout, template prediction, output files) except
  (1) PANELS = this part's panels (4 parts a/b/c/d; generated by analysis/t1lab/t1catb_make_kernel.py);
  (2) model: CatBoost RMSE regressors for speed/vf and flow/lane residuals, depth 8 (CB_IT8 iterations) + depth 10 (CB_IT10)
      averaged 50/50, lr 0.12, l2 10, Bernoulli 0.85, border_count 64 (anubisyy train_state.py family), on at most CB_ROWS
      of the train + transductive rows (random subsample rng 21);
  (3) SMOKE: 60 / 30 iterations.
  Lab (analysis/t1lab/t1div_exp.py + t1div_report.py, 4 panels x 2 months, paired vs mean of 2 LightGBM members):
  see experiments/TRACKER.md EXP_T1_CATB. Output state_submission_FTA.csv is blended into the T1 mix by
  kaggle_jobs/t1_t1dark_swap.py (CATB_MEMBER / W_CATB) before recon + TV.
Previous notes (v13a):
'''

CB_BLOCK = '''from catboost import CatBoostRegressor
CB_IT8, CB_IT10, CB_LR, CB_ROWS, CB_SEED = 2000, 1000, 0.12, 2_400_000, 21


class CBPair:
    """depth-8 + depth-10 CatBoost regressors averaged 50/50 (same interface as a LightGBM booster for predict_variants)."""

    def __init__(self, X, y):
        it8, it10 = (60, 30) if SMOKE else (CB_IT8, CB_IT10)
        self.m = []
        for depth, it in ((8, it8), (10, it10)):
            t = time.time()
            m = CatBoostRegressor(iterations=it, depth=depth, learning_rate=CB_LR, l2_leaf_reg=10, loss_function='RMSE',
                                  thread_count=4, random_seed=20261005, bootstrap_type='Bernoulli', subsample=0.85,
                                  border_count=64, verbose=0, allow_writing_files=False)
            m.fit(X, y)
            self.m.append(m)
            log(f'  catboost depth {depth} it {it} rows {len(y)}: {time.time() - t:.0f}s, peak RSS {peak_gb():.2f} GB')

    def predict(self, X):
        return 0.5 * (self.m[0].predict(X, thread_count=4) + self.m[1].predict(X, thread_count=4))

    def importance(self):
        return 0.5 * (self.m[0].get_feature_importance() + self.m[1].get_feature_importance())

'''

OLD_MODEL = """    MODELS = {'FTA': (lgb.train(pF, lgb.Dataset(XA, YV), NT), lgb.train(pF, lgb.Dataset(XA, YQ), NT), ixD)}
    imp = pd.Series(MODELS['FTA'][0].feature_importance('gain'), index=[cols[i] for i in ixD]).sort_values(ascending=False)
"""
NEW_MODEL = """    if len(XA) > CB_ROWS:
        selc = np.sort(np.random.default_rng(CB_SEED).choice(len(XA), CB_ROWS, replace=False))
        XA, YV, YQ = XA[selc], YV[selc], YQ[selc]; del selc; gc.collect()
    MODELS = {'FTA': (CBPair(XA, YV), CBPair(XA, YQ), ixD)}
    imp = pd.Series(MODELS['FTA'][0].importance(), index=[cols[i] for i in ixD]).sort_values(ascending=False)
"""


def make(part, panels):
    src = open(SRC).read()
    assert src.startswith('"""')
    out = DOC.format(part=part, panels=', '.join(panels)) + src[3:]
    rep = [("PANELS = PANELS[:5]\n", f"PANELS = {panels!r}                     # t1catb part {part}\n"),
           (OLD_MODEL, NEW_MODEL)]
    for a, b in rep:
        assert out.count(a) == 1, a
        out = out.replace(a, b)
    # CatBoost block after the helper functions log / peak_gb (it uses both)
    anchor = '# ------------------------------------------------------------------ loading\n'
    assert out.count(anchor) == 1
    out = out.replace(anchor, CB_BLOCK + '\n' + anchor)
    ast.parse(out)
    path = os.path.join(ROOT, 'kaggle_jobs', f't1_catb_member_{part}.py')
    open(path, 'w').write(out)
    return path


# ------------------------------------------------------------------ swap chain (T1 mix + CatBoost blend, then recon + TV)
SWAP_SRC = os.path.join(ROOT, 'consolidation', 'lineage_src', 'tfb-i4d.py')      # production tfb-i4d (t1_t1dark_swap)
RECON_SRC = os.path.join(ROOT, 'consolidation', 'lineage_src', 'tfb-i4.py')      # production tfb-i4 (swap_fdrecon)


def make_swap(w_catb, base=('tfb-j4', 'submission_J4.csv'), out_name='K1D'):
    s = open(SWAP_SRC).read()
    doc = (f'"""t1catb swap (EXP_T1_CATB) = production tfb-i4d (T1 mix + blackout override) with the CatBoost member blended into\n'
           f'the T1 mix BEFORE the blackout override: mix = (1 - W_CATB) * (W_FD * FD bag + (1 - W_FD) * old bag) + W_CATB * t1catb\n'
           f'(parts tfb-t1catba..d = kaggle_jobs/t1_catb_member_a..d.py); blackout rows then = (1 - W_DARK) * mix + W_DARK * t1bspec\n'
           f'as before. Base file (queue / Task 4 rows) = {base[0]} (final candidate A2). Feed the output to swap_fdrecon_k1.py.\n'
           f'Generated by analysis/t1lab/t1catb_make_kernel.py.\nPrevious notes (tfb-i4d):\n')
    s = doc + s[3:]
    rep = [("BASE_KERNEL, BASE_FILE, OUT_NAME = 'tfb-i2', 'submission_FDRTV.csv', 'T1DARK'\n",
            f"BASE_KERNEL, BASE_FILE, OUT_NAME = {base[0]!r}, {base[1]!r}, {out_name!r}\n"
            f"CATB_MEMBER, CATB_PARTS, W_CATB = 'tfb-t1catb', 'abcd', {w_catb}\n"),
           ("out.loc[iss, 'speed_kmh'] = W_FD * vf_ + (1 - W_FD) * vo; out.loc[iss, 'flow_vph'] = W_FD * qf_ + (1 - W_FD) * qo\n",
            "out.loc[iss, 'speed_kmh'] = W_FD * vf_ + (1 - W_FD) * vo; out.loc[iss, 'flow_vph'] = W_FD * qf_ + (1 - W_FD) * qo\n"
            "# ---- t1catb: CatBoost member blended into the mix on every state row (before the blackout override)\n"
            "vc, qc = load(tuple(f'{CATB_MEMBER}{p}' for p in CATB_PARTS), 'state_submission_FTA.csv')\n"
            "v_m0, q_m0 = out.loc[iss, 'speed_kmh'].to_numpy(), out.loc[iss, 'flow_vph'].to_numpy()\n"
            "print('t1catb parts', CATB_PARTS, '| W_CATB', W_CATB, '| rms catb vs mix: speed', round(float(np.sqrt(np.mean((vc - v_m0) ** 2))), 3),\n"
            "      'flow', round(float(np.sqrt(np.mean((qc - q_m0) ** 2))), 2), '| corr speed', round(float(np.corrcoef(vc, v_m0)[0, 1]), 5))\n"
            "assert np.isfinite(vc).all() and np.isfinite(qc).all() and np.sqrt(np.mean((vc - v_m0) ** 2)) < 5.0, 'catb member looks broken'\n"
            "out.loc[iss, 'speed_kmh'] = (1 - W_CATB) * v_m0 + W_CATB * vc; out.loc[iss, 'flow_vph'] = (1 - W_CATB) * q_m0 + W_CATB * qc\n")]
    for a, b in rep:
        assert s.count(a) == 1, a
        s = s.replace(a, b)
    ast.parse(s)
    p1 = os.path.join(ROOT, 'kaggle_jobs', 't1_catb_swap.py'); open(p1, 'w').write(s)
    r = open(RECON_SRC).read()
    a = "BASE_KERNEL, BASE_FILE = 'tfb-i4d', 'submission_T1DARK.csv'\n"
    assert r.count(a) == 1
    r = r.replace(a, f"BASE_KERNEL, BASE_FILE = 'tfb-k1d', 'submission_{out_name}.csv'   # t1catb chain (was tfb-i4d)\n")
    ast.parse(r)
    p2 = os.path.join(ROOT, 'kaggle_jobs', 'swap_fdrecon_k1.py'); open(p2, 'w').write(r)
    return p1, p2


if __name__ == '__main__':
    allp = [p for v in PARTS.values() for p in v]
    assert sorted(allp) == sorted(['D7_I10_E', 'D7_I10_W', 'D7_I210_E', 'D7_I210_W', 'D7_I405_N', 'D7_I405_S',
                                   'D12_I5_N', 'D12_I5_S', 'D12_I405_N', 'D12_I405_S'])
    for part, panels in PARTS.items():
        print('written + ast OK', make(part, panels))
    import sys
    w = float(sys.argv[1]) if len(sys.argv) > 1 else 0.25
    print('written + ast OK', *make_swap(w), '| W_CATB', w)
