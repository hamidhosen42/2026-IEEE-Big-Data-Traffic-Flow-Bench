"""Generate the round-2 T1 diversity member kernels + swap chain (EXP_T1_XGB passed its pre-registered gate in t1div_lib.py;
EXP_T1_CATBFTA failed and has no kernel).

Members (4 panel parts a/b/c/d as t1catb; source kaggle_jobs/t1_pipeline_v13a.py through analysis/t1lab/t1catb_make_kernel.py
pieces; data loading, darkened train view, row rng 9 / transductive rng 10000 (= the v13 / t1catb rows), 15 % validation
holdout, template prediction and output files unchanged; at most 2.4M train + transductive rows, subsample rng 21 as t1catb):
  xgb      kaggle_jobs/t1_xgb_member_{a..d}.py      XGBoost hist (lab settings: max_depth 9, eta 0.06, 1500 rounds,
           subsample / colsample 0.8, min_child_weight 50, lambda 10, max_bin 256, seed 20261016) on the 94 FD columns
Swap chain on base tfb-k3 (queue / Task 4 rows):
  kaggle_jobs/t1_div2_swap.py   = t1_catb2_swap.py (W_FD bag mix -> 0.65 / 0.35 with mean of 2 CatBoost seeds) then
                                  mix = (1 - W_CAND) mix + W_CAND cand, then blackout override (0.25 mix + 0.75 t1bspec)
  kaggle_jobs/swap_fdrecon_k5.py = swap_fdrecon_k3.py (recon + TV) on the output of t1_div2_swap.py
Usage: t1div2_make_kernel.py xgb <W_CAND> [out=K5D] [slug=tfb-k5d]
"""
import ast, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import t1catb_make_kernel as CB  # noqa: E402

ROOT = CB.ROOT
SLUG = {'xgb': 'tfb-t1xgb'}

DOC = '''"""Task 1 {cand} member ({exp}): {what}, part {part} = {panels}.
Identical to kaggle_jobs/t1_catb_member_{part}.py (= kaggle_jobs/t1_pipeline_v13a.py with this part's panels; data loading,
darkened train view, row rng 9 and transductive rounds rng 10000 = the v13 rows, at most 2.4M train + transductive rows
(subsample rng 21), 15 % validation holdout, template prediction, output files) except the model:
{model}
  Lab: analysis/t1lab/t1div_exp.py arm {cand} + t1div_report.py stand=catb ctrl=base3 (experiments/TRACKER.md {exp}).
  Output state_submission_FTA.csv is blended into the T1 mix by kaggle_jobs/t1_div2_swap.py (CAND_MEMBER / W_CAND).
  Generated by analysis/t1lab/t1div2_make_kernel.py.
Previous notes (v13a):
'''

MODEL_TXT = {
    'xgb': ('EXP_T1_XGB', 'XGBoost hist residual member on the v13 FD feature set (94 columns)',
            '  XGBoost hist regressors for speed/vf and flow/lane residuals, max_depth 9, eta 0.06, 1500 rounds, subsample 0.8,\n'
            '  colsample_bytree 0.8, min_child_weight 50, lambda 10, max_bin 256, seed 20261016 (SMOKE: 40 rounds).'),
}

XGB_BLOCK = '''import xgboost as xgb
XGB_N, XGB_ETA, XGB_DEPTH, CB_ROWS, CB_SEED = 1500, 0.06, 9, 2_400_000, 21


class XGBOne:
    """XGBoost hist regressor (same interface as a LightGBM booster for predict_variants)."""

    def __init__(self, X, y):
        n = 40 if SMOKE else XGB_N
        t = time.time()
        self.nf = X.shape[1]
        prm = dict(tree_method='hist', max_depth=XGB_DEPTH, eta=XGB_ETA, subsample=0.8, colsample_bytree=0.8, min_child_weight=50,
                   reg_lambda=10.0, max_bin=256, objective='reg:squarederror', seed=20261016, nthread=4)
        d = xgb.QuantileDMatrix(X, y, max_bin=256, nthread=4)
        self.m = xgb.train(prm, d, n)
        del d; gc.collect()
        log(f'  xgboost depth {XGB_DEPTH} rounds {n} rows {len(y)}: {time.time() - t:.0f}s, peak RSS {peak_gb():.2f} GB')

    def predict(self, X):
        return self.m.predict(xgb.DMatrix(np.ascontiguousarray(X, dtype=np.float32), nthread=4))

    def importance(self):
        g = self.m.get_score(importance_type='total_gain')            # percent of total gain (CatBoost-like scale)
        v = np.array([g.get(f'f{i}', 0.0) for i in range(self.nf)])
        return 100.0 * v / max(v.sum(), 1e-12)

'''

NEW_MODEL = {
    'xgb': """    if len(XA) > CB_ROWS:
        selc = np.sort(np.random.default_rng(CB_SEED).choice(len(XA), CB_ROWS, replace=False))
        XA, YV, YQ = XA[selc], YV[selc], YQ[selc]; del selc; gc.collect()
    MODELS = {'FTA': (XGBOne(XA, YV), XGBOne(XA, YQ), ixD)}
    imp = pd.Series(MODELS['FTA'][0].importance(), index=[cols[i] for i in ixD]).sort_values(ascending=False)
""",
}


def make_member(cand, part, panels):
    src = open(CB.SRC).read()
    assert src.startswith('"""')
    exp, what, model = MODEL_TXT[cand]
    out = DOC.format(cand=cand, exp=exp, what=what, part=part, panels=', '.join(panels), model=model) + src[3:]
    rep = [("PANELS = PANELS[:5]\n", f"PANELS = {panels!r}                     # t1 {cand} part {part}\n"),
           (CB.OLD_MODEL, NEW_MODEL[cand])]
    for a, b in rep:
        assert out.count(a) == 1, a
        out = out.replace(a, b)
    block = XGB_BLOCK
    anchor = '# ------------------------------------------------------------------ loading\n'
    assert out.count(anchor) == 1
    out = out.replace(anchor, block + '\n' + anchor)
    ast.parse(out)
    path = os.path.join(ROOT, 'kaggle_jobs', f't1_{cand}_member_{part}.py')
    open(path, 'w').write(out)
    return path


def make_swap(cand, w, out_name='K5D', slug='tfb-k5d', recon_name='swap_fdrecon_k5.py'):
    s = open(os.path.join(ROOT, 'kaggle_jobs', 't1_catb2_swap.py')).read()
    exp = MODEL_TXT[cand][0]
    doc = (f'"""T1 diversity swap {out_name} ({exp}, 2026-10-16): = t1_catb2_swap.py (K3D: W_FD bag mix, then 0.65 / 0.35 with the\n'
           f'mean of 2 CatBoost seeds) with the {cand} member ({SLUG[cand]}a..d = kaggle_jobs/t1_{cand}_member_a..d.py) blended in\n'
           f'AFTER the CatBoost blend and BEFORE the blackout override: mix = (1 - W_CAND) * mix + W_CAND * {cand}; blackout rows then\n'
           f'= (1 - W_DARK) * mix + W_DARK * t1bspec as before. Base file (queue / Task 4 rows) = tfb-k3 (best public, final pick A).\n'
           f'Feed the output to {recon_name} (recon + TV). Generated by analysis/t1lab/t1div2_make_kernel.py.\n')
    s = doc + s[3:]
    rep = [("BASE_KERNEL, BASE_FILE, OUT_NAME = 'tfb-j4', 'submission_J4.csv', 'K3D'\n",
            f"BASE_KERNEL, BASE_FILE, OUT_NAME = 'tfb-k3', 'submission_FDRTV.csv', {out_name!r}\n"
            f"CAND_MEMBER, CAND_PARTS, W_CAND = {SLUG[cand]!r}, 'abcd', {w}   # {exp}\n"),
           ("out.loc[iss, 'speed_kmh'] = (1 - W_CATB) * v_m0 + W_CATB * vc; out.loc[iss, 'flow_vph'] = (1 - W_CATB) * q_m0 + W_CATB * qc\n",
            "out.loc[iss, 'speed_kmh'] = (1 - W_CATB) * v_m0 + W_CATB * vc; out.loc[iss, 'flow_vph'] = (1 - W_CATB) * q_m0 + W_CATB * qc\n"
            f"# ---- {exp}: candidate member blended into the mix (incl. CatBoost) on every state row, before the blackout override\n"
            "vx, qx = load(tuple(f'{CAND_MEMBER}{p}' for p in CAND_PARTS), 'state_submission_FTA.csv')\n"
            "v_m1, q_m1 = out.loc[iss, 'speed_kmh'].to_numpy(), out.loc[iss, 'flow_vph'].to_numpy()\n"
            "print('cand', CAND_MEMBER, CAND_PARTS, '| W_CAND', W_CAND, '| rms cand vs mix: speed', round(float(np.sqrt(np.mean((vx - v_m1) ** 2))), 3),\n"
            "      'flow', round(float(np.sqrt(np.mean((qx - q_m1) ** 2))), 2), '| corr speed', round(float(np.corrcoef(vx, v_m1)[0, 1]), 5))\n"
            "assert np.isfinite(vx).all() and np.isfinite(qx).all() and np.sqrt(np.mean((vx - v_m1) ** 2)) < 5.0, 'cand member looks broken'\n"
            "out.loc[iss, 'speed_kmh'] = (1 - W_CAND) * v_m1 + W_CAND * vx; out.loc[iss, 'flow_vph'] = (1 - W_CAND) * q_m1 + W_CAND * qx\n")]
    for a, b in rep:
        assert s.count(a) == 1, a
        s = s.replace(a, b)
    ast.parse(s)
    p1 = os.path.join(ROOT, 'kaggle_jobs', 't1_div2_swap.py'); open(p1, 'w').write(s)
    r = open(os.path.join(ROOT, 'kaggle_jobs', 'swap_fdrecon_k3.py')).read()
    a = "BASE_KERNEL, BASE_FILE = 'tfb-k3d', 'submission_K3D.csv'   # t1catb chain (was tfb-i4d)\n"
    assert r.count(a) == 1
    r = r.replace(a, f"BASE_KERNEL, BASE_FILE = {slug!r}, 'submission_{out_name}.csv'   # {exp} chain (was tfb-k3d)\n")
    ast.parse(r)
    p2 = os.path.join(ROOT, 'kaggle_jobs', recon_name); open(p2, 'w').write(r)
    return p1, p2


if __name__ == '__main__':
    cand, w = sys.argv[1], float(sys.argv[2])
    kw = dict(a.split('=') for a in sys.argv[3:] if '=' in a)
    assert cand in SLUG and 0 < w < 1
    for part, panels in CB.PARTS.items():
        print('written + ast OK', make_member(cand, part, panels))
    print('written + ast OK', *make_swap(cand, w, kw.get('out', 'K5D'), kw.get('slug', 'tfb-k5d')), '| W_CAND', w)
